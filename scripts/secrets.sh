#!/usr/bin/env bash
#
# The OAN secrets and the OpenBao they live in, for one environment.
#
#   ./scripts/secrets.sh dev setup      once per cluster: unseal key, init, KV, auth, policies
#   ./scripts/secrets.sh dev generate   write secrets/secrets-dev.yaml (gitignored)
#   ./scripts/secrets.sh dev push       write it to OpenBao, changed entries only
#   ./scripts/secrets.sh dev pull       rebuild the file from OpenBao when it is lost
#   ./scripts/secrets.sh dev list       what OpenBao holds (names, versions; never values)
#   ./scripts/secrets.sh dev key-ids    after registry-seed: fill keyId, push, restart adapters
#   ./scripts/secrets.sh dev token      print a 15-minute write token, for other tools:
#                                       BAO_TOKEN="$(./scripts/secrets.sh dev token)" ...
#
# Options:
#   generate  --force (re-key everything)  --missing (add only absent keys)  --dry-run
#   push      --only name,name  --dry-run
#   pull      --force  --stdout
#   setup     --init-out FILE (default ~/openbao-<env>-init.json)
#             --unseal-key-file FILE (default ~/openbao-<env>-unseal.key)
#   key-ids   --no-push  --no-restart  --dry-run  --timeout SECONDS
#
# OPENBAO IS THE SOURCE OF TRUTH; the file is a working copy. A lost file is
# recovered with pull: regenerating changes every password and nothing authenticates.
# push, pull, list and key-ids get their own 15-minute operator token unless
# BAO_TOKEN is set. Needs bash, kubectl, yq v4, openssl.
set -euo pipefail

cd "$(dirname "$0")/.."

die() { echo "ERROR: $*" >&2; exit 1; }
info() { echo "-> $*" >&2; }
usage() { sed -n '3,26p' "$0" | cut -c3-; exit "${1:-0}"; }

[[ $# -ge 2 ]] || usage 1
environment="$1" action="$2"; shift 2
[[ -f "config/$environment/global-values.yaml" ]] || die "no such environment: $environment"

force=false missing=false dry_run=false stdout=false push=true restart=true
only="" timeout=600
init_out="$HOME/openbao-$environment-init.json"
unseal_key_file="$HOME/openbao-$environment-unseal.key"
while [[ $# -gt 0 ]]; do
  case "$1" in
    --force) force=true; shift ;;
    --missing) missing=true; shift ;;
    --dry-run) dry_run=true; shift ;;
    --stdout) stdout=true; shift ;;
    --no-push) push=false; shift ;;
    --no-restart) restart=false; shift ;;
    --only) only="${2:?--only needs names}"; shift 2 ;;
    --timeout) timeout="${2:?--timeout needs seconds}"; shift 2 ;;
    --init-out) init_out="${2:?}"; shift 2 ;;
    --unseal-key-file) unseal_key_file="${2:?}"; shift 2 ;;
    -h|--help) usage ;;
    *) die "unknown option: $1" ;;
  esac
done

for cmd in kubectl yq openssl; do
  command -v "$cmd" >/dev/null || die "$cmd is not on PATH"
done

file="secrets/secrets-$environment.yaml"
bao_ns="${OPENBAO_NAMESPACE:-openbao}"
bao_pod="${OPENBAO_POD:-openbao-0}"
operator_sa="openbao-operator"
store="oan/$environment"
pending_prefix="<<PENDING"
# Held back by push while still a placeholder: a placeholder URL would fail silently.
hold_while_pending="grafana-slack"

global() { K="$1" yq '.global[strenv(K)] // ""' "config/$environment/global-values.yaml"; }

# --------------------------------------------------------------------- values

# 9 chars from letters, digits, @ !, with at least one of each class.
password() {
  local length="${1:-9}" pw
  while true; do
    pw="$(LC_ALL=C tr -dc 'A-Za-z0-9@!' </dev/urandom | head -c "$length")"
    [[ "$pw" =~ [A-Za-z] && "$pw" =~ [0-9] && "$pw" =~ [@!] ]] && { printf '%s' "$pw"; return; }
  done
}

# Raw 32-byte halves, base64: the format the adapter decodes. Sets $private, $public.
keypair() {
  local key
  key="$(openssl genpkey -algorithm "$1")"
  private="$(printf '%s\n' "$key" | openssl pkey -outform DER | tail -c 32 | base64)"
  public="$(printf '%s\n' "$key" | openssl pkey -pubout -outform DER | tail -c 32 | base64)"
}

# @ and ! percent-encoded: @ is the userinfo delimiter in a DSN.
dsn() { printf 'postgresql://%s:%s@%s:5432/%s' "$1" "$(printf '%s' "$2" | sed 's/@/%40/g; s/!/%21/g')" "$3" "$4"; }

q() { local s="'"; printf "'%s'" "${1//$s/$s$s}"; }
pending() { q "$pending_prefix: $1>>"; }

# One top-level key per secret, each one entry in OpenBao. "namespaces" is the
# Reflector target list (first is the source), a comment rather than data.
build() {
  local domain="$1" pw
  cat <<EOF
# Generated by scripts/secrets.sh. Values only: one top-level key per secret,
# each one entry in OpenBao under secret/$store/.

# namespaces: postgres, registry
registry-db:
  username: 'registry'
  password: $(q "$(password)")

# namespaces: postgres, keycloak
keycloak-db:
  username: 'keycloak'
  password: $(q "$(password)")

# namespaces: keycloak
keycloak-admin:
  keycloakAdminPassword: $(q "$(password)")

# namespaces: registry, keycloak (admin-api client: Keycloak stores it, the registry presents it)
keycloak-admin-api:
  keycloakAdminClientSecret: $(q "$(password)")

# namespaces: keycloak, registry
registry-seed:
  registrySeedPassword: $(q "$(password)")

# namespaces: registry
registry-default-user:
  registryDefaultUserPassword: $(q "$(password)")

EOF
  pw="$(password)"
  cat <<EOF
# namespaces: postgres, discovery (uri carries the FQDN, so it resolves from discovery)
discovery-db:
  username: 'discovery'
  password: $(q "$pw")
  uri: $(q "$(dsn discovery "$pw" "discovery-db-rw.postgres.svc.cluster.local" discovery)")

# namespaces: postgres (only with enableSuperuserAccess)
postgres-superuser:
  username: 'postgres'
  password: $(q "$(password)")

EOF
  local sign_private sign_public
  keypair ed25519; sign_private="$private" sign_public="$public"
  keypair x25519
  cat <<EOF
# namespaces: network-adapter, federation (one keypair for the whole network)
network-adapter-keys:
  subscriberId: $(q "$domain")
  keyId: $(pending "registry osid, filled in by: secrets.sh $environment key-ids")
  roles: 'consumer,network,provider'
  signingPrivateKey: $(q "$sign_private")
  signingPublicKey: $(q "$sign_public")
  encrPrivateKey: $(q "$private")
  encrPublicKey: $(q "$public")
  vistaarTokenUrl: $(pending "Vistaar login URL")
  pmfbyTokenUrl: $(pending "PMFBY login URL")
  agmarknetTokenUrl: $(pending "Agmarknet login URL")

# namespaces: provider-adapter (upstream credentials the provider config names by variable)
provider-upstream:
  MAUSAMGRAM_AUTH: $(pending "IMD Mausamgram bearer token")
  VISTAAR_CLIENT_ID: $(pending "Bharat Vistaar oauth2 client id")
  VISTAAR_CLIENT_SECRET: $(pending "Bharat Vistaar oauth2 client secret")
  AGMARKNET_ACCESS_NAME: $(pending "Agmarknet access name")
  AGMARKNET_PASSWORD: $(pending "Agmarknet password")

# namespaces: network-adapter (single-adapter) or provider-adapter (multi-adapter)
provider-pmfby:
  PMFBY_ACCESS_UID: $(pending "issued by PMFBY")
  PMFBY_ACCESS_PWD: $(pending "issued by PMFBY")

# namespaces: network-adapter (single-adapter) or provider-adapter (multi-adapter)
provider-pmkisan:
  PMKISAN_GRIEVANCE_KEY: $(pending "grievance AES-256 key, 64 hex chars, issued by PM-KISAN")
  PMKISAN_GRIEVANCE_IV: $(pending "grievance AES-GCM nonce, 24 hex chars, issued by PM-KISAN")
  PMKISAN_SERVICE_TOKEN: $(pending "grievance service token, issued by PM-KISAN")
  PMKISAN_OTP_TOKEN: $(pending "chatbot service token, issued by PM-KISAN")

# namespaces: observability (ClickStack's ClickHouse users; nothing types them, so long)
clickstack-clickhouse:
  appUserPassword: $(q "$(password 24)")
  otelUserPassword: $(q "$(password 24)")

# namespaces: observability (ClickHouse user otel, for grafana and otel-collector)
clickhouse-otel:
  password: $(q "$(password 24)")

# namespaces: observability
grafana-admin:
  admin-user: 'admin'
  admin-password: $(q "$(password)")

# namespaces: observability (issued by Slack; push holds it back until filled in)
grafana-slack:
  url: $(pending "Slack incoming webhook URL for alerts")

# namespaces: knowledge-provider (MinIO root user; the api and worker log in with it)
knowledge-provider-minio-credentials:
  access-key: 'knowledge-provider'
  secret-key: $(q "$(openssl rand -hex 16)")

# namespaces: knowledge-provider (Keycloak console login)
knowledge-provider-keycloak-admin:
  password: $(q "$(password)")

# namespaces: knowledge-provider (Qdrant API key; qdrant, api and worker read it)
knowledge-provider-qdrant:
  api-key: $(q "$(openssl rand -hex 24)")

EOF
  # One Redis password, two entries: clients read redis/password; redis-config is
  # appended whole to redis.conf, so it must hold only config lines.
  pw="$(openssl rand -hex 24)"
  cat <<EOF
# namespaces: redis (+ the namespaces of its clients)
redis:
  password: $(q "$pw")

# namespaces: redis (mounted into the Redis pod, appended to redis.conf)
redis-config:
  requirepass.conf: $(q "requirepass $pw")

# namespaces: langfuse (pinned: chart-generated values would rotate on every Argo CD sync)
langfuse-app-keys:
  salt: $(q "$(openssl rand -base64 32)")
  encryption-key: $(q "$(openssl rand -hex 32)")
  nextauth-secret: $(q "$(openssl rand -base64 32)")

# namespaces: langfuse
langfuse-clickhouse:
  password: $(q "$(openssl rand -hex 16)")

# namespaces: langfuse (key is the Valkey ACL user name)
langfuse-redis:
  default: $(q "$(openssl rand -hex 16)")

# namespaces: langfuse
langfuse-minio-credentials:
  access-key: 'langfuse'
  secret-key: $(q "$(openssl rand -hex 16)")
EOF
}

# Written 0600 from the start, so values are never readable by others.
write_file() {
  mkdir -p "$(dirname "$file")"
  (umask 077; cat > "$file.tmp.$$") && mv "$file.tmp.$$" "$file"
}

# -------------------------------------------------------------------- OpenBao

# The token goes in on stdin, never argv: exec arguments reach the API server audit log.
_bao_exec() {
  kubectl -n "$bao_ns" exec -i "$bao_pod" -c openbao -- \
    sh -c 'IFS= read -r BAO_TOKEN; export BAO_TOKEN; exec bao "$@"' bao "$@"
}
bao() { printf '%s\n' "${BAO_TOKEN:-}" | _bao_exec "$@"; }
bao_in() { { printf '%s\n' "${BAO_TOKEN:-}"; cat; } | _bao_exec "$@"; }

bao_status() { bao status -format=json 2>/dev/null | yq -p=json ".$1" 2>/dev/null || true; }

# A data volume older than the StatefulSet survived an earlier install, so it may
# hold a store; one the current StatefulSet created is empty until the key exists.
data_volume_predates_install() {
  local volume_created statefulset_created
  volume_created="$(kubectl -n "$bao_ns" get pvc "data-$bao_pod" \
    -o jsonpath='{.metadata.creationTimestamp}' 2>/dev/null)" || return 1
  statefulset_created="$(kubectl -n "$bao_ns" get statefulset "${bao_pod%-*}" \
    -o jsonpath='{.metadata.creationTimestamp}' 2>/dev/null)" || return 0
  [[ "$volume_created" < "$statefulset_created" ]]
}

# A 15-minute token as role oan-<env>-operator, from a 10-minute ServiceAccount
# token. Minting that needs the cluster's admin access level.
login() {
  [[ -n "${BAO_TOKEN:-}" ]] && return
  local jwt
  jwt="$(kubectl -n "$bao_ns" create token "$operator_sa" --duration=10m)" \
    || die "could not mint a token for $bao_ns/$operator_sa (needs admin access, and setup must have run)"
  BAO_TOKEN="$(printf '%s' "$jwt" | kubectl -n "$bao_ns" exec -i "$bao_pod" -c openbao -- \
    bao write -field=token auth/kubernetes/login role="oan-$environment-operator" jwt=-)" \
    || die "login as oan-$environment-operator failed; has setup run?"
  export BAO_TOKEN
}

require_bao() {
  login
  local initialized
  initialized="$(bao_status initialized)"
  [[ "$initialized" == true || "$initialized" == false ]] \
    || die "could not reach OpenBao in $bao_ns/$bao_pod (context $(kubectl config current-context 2>/dev/null))"
  [[ "$initialized" == true ]] || die "OpenBao is not initialised; run: secrets.sh $environment setup"
  [[ "$(bao_status sealed)" == false ]] || die "OpenBao is sealed; check Secret/openbao-unseal-key"
  info "OpenBao $bao_ns/$bao_pod, context $(kubectl config current-context)"
}

# The entry as sorted compact JSON, "" if absent; any other failure is fatal,
# so push never "creates" over a value it simply could not read.
kv_get() {
  local out code=0
  out="$(bao kv get -mount=secret -format=json "$store/$1" 2>&1)" || code=$?
  if [[ $code -ne 0 ]]; then
    [[ $code -eq 2 && "$out" == *"No value found"* ]] && return 0
    die "reading secret/$store/$1: $out"
  fi
  printf '%s' "$out" | yq -p=json -o=json -I=0 '.data.data | sort_keys(.)'
}

kv_list() {
  local out code=0
  out="$(bao kv list -mount=secret -format=json "$store/" 2>&1)" || code=$?
  if [[ $code -ne 0 ]]; then
    [[ $code -eq 2 && "$out" == *"No value found"* ]] && return 0
    die "listing secret/$store/: $out"
  fi
  printf '%s' "$out" | yq -p=json '.[] | select(test("/$") | not)'
}

# -------------------------------------------------------------------- actions

do_setup() {
  command -v openssl >/dev/null || die "openssl is not on PATH"
  # 1. The unseal key: never in git, and it must outlive the cluster.
  kubectl get namespace "$bao_ns" >/dev/null 2>&1 || kubectl create namespace "$bao_ns" >/dev/null
  if kubectl -n "$bao_ns" get secret openbao-unseal-key >/dev/null 2>&1; then
    info "unseal key Secret exists"
  else
    if [[ -f "$unseal_key_file" ]]; then
      info "reusing the unseal key in $unseal_key_file"
    elif data_volume_predates_install; then
      die "OpenBao already has data but no unseal key Secret, and $unseal_key_file does not
  exist. A new key would not open that store; restore the original and re-run."
    else
      info "generating the unseal key -> $unseal_key_file"
      (umask 077; openssl rand -out "$unseal_key_file" 32)
    fi
    kubectl -n "$bao_ns" create secret generic openbao-unseal-key \
      --from-file=unseal.key="$unseal_key_file" >/dev/null
    info "created Secret $bao_ns/openbao-unseal-key; move $unseal_key_file into the password manager"
  fi

  # 2. Init. No JSON from status means OpenBao was not reached, not "uninitialised".
  local initialized="" _
  info "waiting for $bao_ns/$bao_pod"
  for _ in $(seq 1 120); do
    initialized="$(bao_status initialized)"
    [[ "$initialized" == true || "$initialized" == false ]] && break
    sleep 5
  done
  [[ "$initialized" == true || "$initialized" == false ]] || die "could not reach OpenBao in $bao_ns/$bao_pod"
  # Already configured if the operator login works: leave it, and never read the root token.
  if [[ "$initialized" == true && -z "${BAO_TOKEN:-}" ]] && (login) >/dev/null 2>&1; then
    info "OpenBao is initialised and configured; nothing to do"
    return
  fi
  if [[ "$initialized" == false ]]; then
    [[ ! -e "$init_out" ]] || die "$init_out exists; refusing to overwrite what may be the only root token"
    info "initialising OpenBao"
    (umask 077; bao operator init -format=json > "$init_out.partial") \
      || { rm -f "$init_out.partial"; die "bao operator init failed"; }
    mv "$init_out.partial" "$init_out"
    info "root token and recovery keys written to $init_out; move them off this machine"
  fi
  if [[ -z "${BAO_TOKEN:-}" ]]; then
    [[ -f "$init_out" ]] || die "set BAO_TOKEN (root), or pass --init-out with the init output"
    BAO_TOKEN="$(yq -p=json '.root_token // ""' "$init_out")"
    [[ -n "$BAO_TOKEN" ]] || die "$init_out has no root_token; set BAO_TOKEN instead"
  fi
  export BAO_TOKEN
  for _ in $(seq 1 30); do [[ "$(bao_status sealed)" == false ]] && break; sleep 2; done
  [[ "$(bao_status sealed)" == false ]] || die "OpenBao is still sealed; check the unseal key Secret is mounted"

  # 3. KV v2 and Kubernetes auth.
  bao secrets list -format=json | yq -p=json -e 'has("secret/")' >/dev/null 2>&1 \
    || { info "mounting kv-v2 at secret/"; bao secrets enable -path=secret kv-v2 >/dev/null; }
  bao auth list -format=json | yq -p=json -e 'has("kubernetes/")' >/dev/null 2>&1 \
    || { info "enabling kubernetes auth"; bao auth enable kubernetes >/dev/null; }
  bao write auth/kubernetes/config kubernetes_host="https://kubernetes.default.svc:443" >/dev/null

  # 4. External Secrets: read-only on this environment.
  info "writing policy oan-$environment-read and role external-secrets"
  bao_in policy write "oan-$environment-read" - >/dev/null <<EOF
path "secret/data/$store/*" {
  capabilities = ["read"]
}
EOF
  bao write auth/kubernetes/role/external-secrets \
    bound_service_account_names=external-secrets \
    bound_service_account_namespaces=external-secrets \
    audience="https://kubernetes.default.svc" \
    token_policies="oan-$environment-read" token_ttl=1h >/dev/null

  # 5. The snapshot CronJob: read on the snapshot endpoint only.
  info "writing policy and role snapshot"
  bao_in policy write snapshot - >/dev/null <<EOF
path "sys/storage/raft/snapshot" {
  capabilities = ["read"]
}
EOF
  bao write auth/kubernetes/role/snapshot \
    bound_service_account_names=openbao-snapshot bound_service_account_namespaces="$bao_ns" \
    token_policies=snapshot token_ttl=10m >/dev/null

  # 6. People: write on this environment through the operator role, not the root token.
  info "writing policy oan-$environment-write and role oan-$environment-operator"
  bao_in policy write "oan-$environment-write" - >/dev/null <<EOF
path "secret/data/$store/*" {
  capabilities = ["create", "update", "read"]
}
path "secret/metadata/$store/*" {
  capabilities = ["read", "list"]
}
EOF
  kubectl -n "$bao_ns" create serviceaccount "$operator_sa" --dry-run=client -o yaml | kubectl apply -f - >/dev/null
  bao write "auth/kubernetes/role/oan-$environment-operator" \
    bound_service_account_names="$operator_sa" bound_service_account_namespaces="$bao_ns" \
    token_policies="oan-$environment-write" token_ttl=15m token_max_ttl=15m >/dev/null
  info "done. Next: ./scripts/secrets.sh $environment generate && ./scripts/secrets.sh $environment push"
}

do_generate() {
  local domain body
  domain="$(global domain)"
  [[ -n "$domain" ]] || die "config/$environment/global-values.yaml has no domain"
  body="$(build "$domain")"
  if [[ -f "$file" && "$missing" == true ]]; then
    # Existing values win; only secrets and keys the file lacks are added.
    body="$(printf '%s\n' "$body" | yq ea 'select(fi == 0) * select(fi == 1)' - "$file")"
  elif [[ -f "$file" && "$force" == false ]]; then
    die "$file already exists. Not overwriting it: regenerating replaces every password
  and keypair while the cluster keeps the old ones.
    lost the file?     ./scripts/secrets.sh $environment pull
    new secret added?  ./scripts/secrets.sh $environment generate --missing
    re-key everything: ./scripts/secrets.sh $environment generate --force"
  fi
  if [[ "$dry_run" == true ]]; then
    printf '%s\n' "$body"; info "dry run; $file not written"; return
  fi
  printf '%s\n' "$body" | write_file
  info "wrote $file (0600)"
  local outstanding
  outstanding="$(yq '.. | select(tag == "!!str" and test("^<<PENDING")) | path | join("/")' "$file")"
  if [[ -n "$outstanding" ]]; then
    echo "Outstanding, assigned by another system (edit the file before pushing):" >&2
    printf '  %s\n' $outstanding >&2
    echo "  keyId is filled in after seeding by: ./scripts/secrets.sh $environment key-ids" >&2
  fi
  info "next: ./scripts/secrets.sh $environment push"
}

do_push() {
  [[ -f "$file" ]] || die "no $file. Create it: secrets.sh $environment generate, or recover it: secrets.sh $environment pull"
  require_bao
  local names name current wanted verb written=0 placeholders
  names="$(yq 'keys | .[]' "$file")"
  if [[ -n "$only" ]]; then
    names="$(printf '%s\n' "$names" | grep -Fx -f <(tr ',' '\n' <<<"$only") || true)"
  fi
  [[ -n "$names" ]] || die "nothing to push${only:+ matching --only $only}"

  placeholders="$(for name in $names; do
    N="$name" yq '.[strenv(N)] | to_entries | .[] | select(.value | test("^<<PENDING")) | strenv(N) + "/" + .key' "$file"
  done)"
  if [[ -n "$placeholders" ]]; then
    echo "WARNING: still placeholders, pushed as placeholder text:" >&2
    printf '  %s\n' $placeholders >&2
  fi

  info "$(wc -w <<<"$names" | tr -d ' ') secret(s) under secret/$store/"
  for name in $names; do
    if [[ " $hold_while_pending " == *" $name "* ]] \
        && [[ "$(N="$name" yq '[.[strenv(N)][] | test("^<<PENDING")] | all' "$file")" == true ]]; then
      echo "   skipped $name: still a placeholder" >&2; continue
    fi
    wanted="$(N="$name" yq -o=json -I=0 '.[strenv(N)] | sort_keys(.)' "$file")"
    current="$(kv_get "$name")"
    if [[ "$current" == "$wanted" ]]; then
      printf '   %-40s unchanged\n' "secret/$store/$name"; continue
    fi
    verb="$([[ -n "$current" ]] && echo "new version" || echo created)"
    if [[ "$dry_run" == true ]]; then
      printf '   %-40s would be %s\n' "secret/$store/$name" "$verb"; continue
    fi
    printf '%s' "$wanted" | bao_in kv put -mount=secret "$store/$name" - >/dev/null \
      || die "writing secret/$store/$name failed"
    printf '   %-40s %s\n' "secret/$store/$name" "$verb"
    written=$((written + 1))
  done
  [[ "$dry_run" == true ]] && { info "dry run; nothing written"; return; }
  [[ $written -gt 0 ]] || { info "nothing changed"; return; }
  info "ESO picks these up within its refresh interval; to have them now:
   kubectl -n external-secrets annotate externalsecret --all force-sync=\$(date +%s) --overwrite"
}

do_pull() {
  require_bao
  local names name body
  names="$(kv_list)"
  [[ -n "$names" ]] || die "nothing under secret/$store/"
  body="$({
    echo "# Pulled from OpenBao secret/$store/. OpenBao is the source of truth."
    for name in $names; do
      echo
      kv_get "$name" | N="$name" yq -p=json -P '{strenv(N): .} | (.. | select(tag == "!!str")) style="single"'
    done
  })"
  if [[ "$stdout" == true ]]; then printf '%s\n' "$body"; return; fi
  [[ ! -f "$file" || "$force" == true ]] || die "$file exists; --force to replace it, or --stdout"
  printf '%s\n' "$body" | write_file
  info "wrote $file (0600), $(wc -w <<<"$names" | tr -d ' ') secrets"
}

do_list() {
  require_bao
  local names name
  names="$(kv_list)"
  [[ -n "$names" ]] || { info "nothing under secret/$store/"; return; }
  printf '%-32s %7s  %s\n' Name Version Changed
  for name in $names; do
    bao kv metadata get -mount=secret -format=json "$store/$name" 2>/dev/null \
      | N="$name" yq -p=json '[strenv(N), .data.current_version, .data.updated_time] | join(" ")' \
      | awk '{ printf "%-32s %7s  %s\n", $1, $2, $3 }'
  done
}

# The registry assigns keyId (an osid) when registry-seed writes the public key,
# so it is read back from the seed Job's log after seeding.
do_key_ids() {
  [[ -f "$file" ]] || die "no $file"
  [[ "$push" == false || "$dry_run" == true ]] || login
  local job pod log roles="" role osid current
  job="$(kubectl -n registry get jobs -l app.kubernetes.io/name=registry-seed \
          -o jsonpath='{.items[-1:].metadata.name}' 2>/dev/null || true)"
  [[ -n "$job" ]] || die "no registry-seed Job in namespace registry; has Argo CD synced registry-seed?"
  info "waiting for job/$job (up to ${timeout}s)"
  kubectl -n registry wait --for=condition=complete "job/$job" --timeout="${timeout}s" >/dev/null \
    || die "seeding did not finish: kubectl -n registry logs job/$job"
  # A retried Job keeps its failed pods, and "logs job/" may pick one of those.
  pod="$(kubectl -n registry get pods -l "job-name=$job" --field-selector=status.phase=Succeeded \
          -o name | head -1)"
  [[ -n "$pod" ]] || die "job/$job completed but has no Succeeded pod: kubectl -n registry get pods -l job-name=$job"
  log="$(kubectl -n registry logs "$pod")"

  # One line per adapter:  network   keyId: 1-6bffc477-...
  while read -r role osid; do
    [[ -n "$role" ]] || continue
    roles="$roles $role"
    current="$(R="$role-adapter-keys" yq '.[strenv(R)].keyId // ""' "$file")"
    if [[ -z "$current" ]]; then
      die "no keyId under $role-adapter-keys in $file"
    elif [[ "$current" == "$osid" ]]; then
      info "$role-adapter-keys/keyId already $osid"
    elif [[ "$current" != "$pending_prefix"* ]]; then
      die "$role-adapter-keys/keyId is $current but the registry reports $osid. An osid is
  never reassigned: the registry was rebuilt (reset keyId to a <<PENDING value and
  re-run), or this file belongs to another environment."
    elif [[ "$dry_run" == true ]]; then
      info "would set $role-adapter-keys/keyId = $osid"
    else
      R="$role-adapter-keys" V="$osid" yq -i '.[strenv(R)].keyId = strenv(V) | .[strenv(R)].keyId style="single"' "$file"
      chmod 600 "$file"
      info "set $role-adapter-keys/keyId = $osid"
    fi
  done < <(printf '%s\n' "$log" | awk '/keyId:/ {print $1, $3}')
  [[ -n "$roles" ]] || die "the Job reported no keyIds; its log ends:
$(printf '%s\n' "$log" | tail -20)"
  [[ "$dry_run" == true ]] && { info "dry run; nothing written"; return; }

  if [[ "$push" == true ]]; then
    only="$(for role in $roles; do printf '%s-adapter-keys,' "$role"; done)"
    only="${only%,}"
    do_push
  fi
  # The adapter reads its keys at pod start only.
  if [[ "$restart" == true ]]; then
    for role in $roles; do
      local ns="$role-adapter"
      if kubectl -n "$ns" get "deployment/$role-adapter" >/dev/null 2>&1; then
        kubectl -n "$ns" rollout restart "deployment/$role-adapter" >/dev/null && info "restarted $role-adapter"
      fi
    done
  fi
}

case "$action" in
  setup) do_setup ;;
  generate) do_generate ;;
  push) do_push ;;
  pull) do_pull ;;
  list) do_list ;;
  key-ids) do_key_ids ;;
  # stdout carries only the token, so it can be captured.
  token) login; printf '%s\n' "$BAO_TOKEN" ;;
  *) usage 1 ;;
esac
